-- Migrasi 2026-10-22 — Server utama di Raspberry Pi: identitas perangkat,
-- API key per perangkat (di-hash), antrean perintah aktuator, status E-STOP.
-- Idempoten: CREATE TABLE IF NOT EXISTS + INSERT ... ON CONFLICT DO NOTHING.
-- Forward-only: hanya tabel baru + parameter dosis baru; tidak menyentuh tabel lama.
-- ============================================================================
BEGIN;

-- ── A. perangkat — katalog sudah ada (2026-10-22_02_rapikan_skema); lengkapi untuk 2 ESP32 ──
-- Tambah kolom peran & telemetri ringan. Baris lama (esp32-a) dibiarkan apa adanya (peran NULL).
ALTER TABLE perangkat ADD COLUMN IF NOT EXISTS peran        varchar(16);
ALTER TABLE perangkat ADD COLUMN IF NOT EXISTS rssi         smallint;
ALTER TABLE perangkat ADD COLUMN IF NOT EXISTS uptime_detik integer;
ALTER TABLE perangkat ADD COLUMN IF NOT EXISTS estop_aktif  boolean;
ALTER TABLE perangkat ADD COLUMN IF NOT EXISTS ip_terakhir  varchar(45);
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'perangkat_peran_cek') THEN
    ALTER TABLE perangkat ADD CONSTRAINT perangkat_peran_cek CHECK (peran IS NULL OR peran IN ('sensor', 'aktuator'));
  END IF;
END $$;
COMMENT ON COLUMN perangkat.peran IS 'sensor = baca & kirim data sensor; aktuator = ambil perintah (dosing, pompa, solenoid). NULL = perangkat lama.';

INSERT INTO perangkat (kode, nama, jenis, peran, keterangan) VALUES
    ('sensor-01',   'ESP32 Sensor (pH, EC/TDS, suhu, kelembapan)', 'ESP32', 'sensor',
        'Membaca semua sensor, mengirim ke server Pi tiap 5 detik.'),
    ('aktuator-01', 'ESP32 Aktuator (dosing, pompa, solenoid)',     'ESP32', 'aktuator',
        'Mengambil perintah dari server Pi dan mengeksekusinya dengan pagar keselamatan firmware.')
ON CONFLICT (kode) DO NOTHING;

-- ── B. api_keys — kunci per perangkat / per klien (hanya HASH yang disimpan) ──
CREATE TABLE IF NOT EXISTS api_keys (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama              varchar(80)  NOT NULL,
    prefix            varchar(16)  NOT NULL,
    hash              char(64)     NOT NULL,
    scope             text[]       NOT NULL,
    perangkat_kode    varchar(32)  REFERENCES perangkat(kode) ON DELETE CASCADE,
    aktif             boolean      DEFAULT true NOT NULL,
    kedaluwarsa_pada  timestamp without time zone,
    terakhir_dipakai  timestamp without time zone,
    ip_terakhir       varchar(45),
    dibuat_pada       timestamp without time zone DEFAULT now() NOT NULL,
    dicabut_pada      timestamp without time zone,
    CONSTRAINT api_keys_prefix_unik UNIQUE (prefix)
);
COMMENT ON TABLE api_keys IS 'Kunci API. Nilai kunci TIDAK disimpan — hanya SHA-256. Kunci tampil sekali saat dibuat.';

-- ── C. perintah_aktuator — antrean perintah server → ESP32 aktuator ──────────
CREATE TABLE IF NOT EXISTS perintah_aktuator (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perangkat_kode    varchar(32)  NOT NULL REFERENCES perangkat(kode) ON DELETE CASCADE,
    tipe              varchar(24)  NOT NULL,
    parameter         jsonb        DEFAULT '{}'::jsonb NOT NULL,
    status            varchar(12)  DEFAULT 'menunggu' NOT NULL,
    sumber            varchar(16)  NOT NULL,
    dibuat_oleh       bigint,
    alasan            varchar(200),
    kedaluwarsa_pada  timestamp without time zone NOT NULL,
    dibuat_pada       timestamp without time zone DEFAULT now() NOT NULL,
    dikirim_pada      timestamp without time zone,
    selesai_pada      timestamp without time zone,
    hasil             jsonb,
    CONSTRAINT perintah_status_cek CHECK (status IN ('menunggu', 'dikirim', 'selesai', 'gagal', 'batal', 'kedaluwarsa')),
    CONSTRAINT perintah_sumber_cek CHECK (sumber IN ('pengguna', 'otomasi', 'ai', 'sistem'))
);
CREATE INDEX IF NOT EXISTS idx_perintah_antre ON perintah_aktuator (perangkat_kode, status, id);
CREATE INDEX IF NOT EXISTS idx_perintah_dibuat ON perintah_aktuator (dibuat_pada DESC);

-- ── D. aktuator_state — latch E-STOP (dan penanda sistem lain) ──────────────
CREATE TABLE IF NOT EXISTS aktuator_state (
    kunci       varchar(32) PRIMARY KEY,
    nilai       varchar(64) NOT NULL,
    diubah_pada timestamp without time zone DEFAULT now() NOT NULL
);
INSERT INTO aktuator_state (kunci, nilai) VALUES ('estop', '0') ON CONFLICT (kunci) DO NOTHING;

-- ── E. pagar dosis tambahan (pH) — boleh diubah lewat /konfigurasi-dosis ────
INSERT INTO konfigurasi_dosis (param, nilai, satuan, keterangan, sumber) VALUES
    ('maks_ml_ph_per_suntikan', 10,  'mL', 'Batas pH Up/Down per suntikan (pagar server; firmware punya batas sendiri)', 'Server Pi 2026-10-22'),
    ('ml_ph_per_langkah',        5,  'mL', 'Langkah dosis pH otomasi (kecil, bertahap, baca ulang)',                      'Server Pi 2026-10-22'),
    ('maks_ml_bilas_per_perintah', 500, 'mL', 'Batas volume bilas per perintah',                                            'Server Pi 2026-10-22')
ON CONFLICT (param) DO NOTHING;

COMMIT;
