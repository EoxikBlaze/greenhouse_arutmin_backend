BEGIN;

CREATE TABLE IF NOT EXISTS target_nutrisi (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    id_tanaman    bigint,
    tahap         varchar(32) NOT NULL,
    umur_min_hari integer,
    umur_max_hari integer,
    ec_min_ppm    numeric(8,2),
    ec_max_ppm    numeric(8,2),
    ph_min        numeric(4,2),
    ph_max        numeric(4,2),
    status        varchar(24) DEFAULT 'menunggu_konfirmasi' NOT NULL,
    keterangan    text,
    sumber        varchar(120),
    updated_at    timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT target_nutrisi_pkey PRIMARY KEY (id),
    CONSTRAINT target_nutrisi_id_tanaman_foreign
        FOREIGN KEY (id_tanaman) REFERENCES tanamen (id_tanaman) ON DELETE CASCADE,
    CONSTRAINT target_nutrisi_status_check
        CHECK (status IN ('menunggu_konfirmasi', 'aktif', 'kadaluarsa')),
    CONSTRAINT target_nutrisi_rentang_check
        CHECK (
            (ec_min_ppm IS NULL OR ec_max_ppm IS NULL OR ec_min_ppm <= ec_max_ppm)
        AND (ph_min    IS NULL OR ph_max    IS NULL OR ph_min    <= ph_max)
        AND (umur_min_hari IS NULL OR umur_max_hari IS NULL OR umur_min_hari <= umur_max_hari)
        )
);

-- Setpoint global (id_tanaman NULL) unik per tahap; setpoint per tanaman unik
-- per (tanaman, tahap, umur awal). Ekspresi COALESCE agar NULL ikut unik.
CREATE UNIQUE INDEX IF NOT EXISTS uq_target_nutrisi_global
    ON target_nutrisi (tahap) WHERE id_tanaman IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_target_nutrisi_tanaman
    ON target_nutrisi (id_tanaman, tahap, COALESCE(umur_min_hari, -1))
    WHERE id_tanaman IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_target_nutrisi_status
    ON target_nutrisi (status);

COMMENT ON TABLE target_nutrisi IS
    'Setpoint EC/pH per jenis tanaman per umur/tahap — Perancangan FINAL Lampiran B par.249 (nilai ditentukan tim website)';
COMMENT ON COLUMN target_nutrisi.id_tanaman IS
    'NULL = target global untuk semua tanaman; terisi = override per jenis tanaman (daun bawang, selada, pakcoy — seksi 1.1 par.14)';
COMMENT ON COLUMN target_nutrisi.tahap IS
    'Semai | Peremajaan | Pendewasaan — mengikuti sikluses.nama_siklus di DB (Lampiran B menyebut "per umur/tahap")';
COMMENT ON COLUMN target_nutrisi.status IS
    'menunggu_konfirmasi = nilai masih NULL (Lampiran B); aktif = sudah disetujui tim website; kadaluarsa = diganti versi baru';

-- Seed placeholder: 3 tahap siklus yang ada di DB (sikluses.nama_siklus) —
-- nilai EC/ph NULL karena dokumen menulis "…" (ditentukan tim website).
INSERT INTO target_nutrisi (id_tanaman, tahap, status, keterangan, sumber)
SELECT NULL, v.tahap, 'menunggu_konfirmasi',
       'Nilai EC/pH BELUM DITENTUKAN — menunggu kesepakatan tim website (Lampiran B par.249); pagar EC sementara 400-1.250 ppm (par.251)',
       'Perancangan_Sistem_IoT_Hidroponik_FINAL.docx Lampiran B par.249'
FROM (VALUES ('Semai'), ('Peremajaan'), ('Pendewasaan')) AS v(tahap)
WHERE NOT EXISTS (
    SELECT 1 FROM target_nutrisi t
    WHERE t.id_tanaman IS NULL AND t.tahap = v.tahap
);

COMMIT;

