-- Idempoten: CREATE TABLE/INDEX IF NOT EXISTS + INSERT ... WHERE NOT EXISTS.
-- Forward-only: tabel baru; kolom min/max tanaman sengaja NULL (nilai belum
--           ditentukan dokumen → keputusan tim website, LIHAT LAPORAN).
