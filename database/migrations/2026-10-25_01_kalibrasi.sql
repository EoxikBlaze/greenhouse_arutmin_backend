-- MIGRASI — halaman kalibrasi alat IoT: jadwal, riwayat, dan konstanta firmware
-- Tanggal : 2026-10-25
-- Masalah : kalibrasi_sensor hanya berisi daftar metode (dokumen perancangan); terakhir_dikalibrasi
--           selalu kosong, tidak ada riwayat, dan konstanta firmware (PH_V7/PH_V4/TDS_FAKTOR_KOREKSI di
--           firmware/sensor/sensor.ino) hanya ada di kode.
-- Solusi  : kolom label, perangkat, toleransi, konstanta (jsonb) + tabel kalibrasi_log. Sensor suhu air
--           dan suhu/kelembapan udara ditambahkan (dibandingkan dengan alat referensi tiap 90 hari).
-- Idempoten.
BEGIN;

ALTER TABLE kalibrasi_sensor ADD COLUMN IF NOT EXISTS label varchar(64);
ALTER TABLE kalibrasi_sensor ADD COLUMN IF NOT EXISTS perangkat_kode varchar(32);
ALTER TABLE kalibrasi_sensor ADD COLUMN IF NOT EXISTS toleransi numeric(10,3);
ALTER TABLE kalibrasi_sensor ADD COLUMN IF NOT EXISTS konstanta jsonb;
ALTER TABLE kalibrasi_sensor DROP CONSTRAINT IF EXISTS kalibrasi_sensor_perangkat_fk;
ALTER TABLE kalibrasi_sensor ADD CONSTRAINT kalibrasi_sensor_perangkat_fk
  FOREIGN KEY (perangkat_kode) REFERENCES perangkat(kode) ON DELETE SET NULL ON UPDATE CASCADE;

INSERT INTO kalibrasi_sensor (sensor, metode, satuan, periode_hari_min, periode_hari_max, keterangan, sumber) VALUES
  ('suhu_air', 'Bandingkan dengan termometer referensi di air yang sama', '°C', 90, 90,
   'Selisih ≤ 0,5 °C; suhu dipakai untuk kompensasi EC', 'Praktik umum (perangkat DS18B20)'),
  ('suhu_udara', 'Bandingkan dengan termo-higrometer referensi di titik yang sama', '°C', 90, 90,
   'Suhu selisih ≤ 1 °C; kelembapan selisih ≤ 5 %', 'Praktik umum (sensor suhu & kelembapan udara)')
ON CONFLICT (sensor) DO NOTHING;

-- perangkat diisi hanya bila kodenya terdaftar (instalasi baru bisa punya kode berbeda)
UPDATE kalibrasi_sensor k SET label = v.label, toleransi = coalesce(k.toleransi, v.tol),
       perangkat_kode = coalesce(k.perangkat_kode, (SELECT kode FROM perangkat WHERE kode = v.perangkat)),
       konstanta = coalesce(k.konstanta, v.konstanta)
  FROM (VALUES
    ('ph', 'Sensor pH', 0.1, 'sensor-01', '{"PH_V7": 2.5, "PH_V4": 3.05}'::jsonb),
    ('ec', 'Sensor EC / TDS', 50, 'sensor-01', '{"TDS_FAKTOR_KOREKSI": 1.0}'::jsonb),
    ('suhu_air', 'Sensor suhu air', 0.5, 'sensor-01', NULL),
    ('suhu_udara', 'Sensor suhu & kelembapan udara', 1, 'sensor-01', NULL),
    ('pulsa_peristaltik', 'Pompa peristaltik (mL/detik)', NULL, 'aktuator-01', NULL),
    ('durasi_bilas', 'Pompa bilas', NULL, 'aktuator-01', NULL),
    ('waktu_isi_botol', 'Pompa celup botol sampel', NULL, 'aktuator-01', NULL),
    ('mixing', 'Waktu aduk (mixing)', NULL, 'aktuator-01', NULL),
    ('bilas_anti_endapan', 'Bilas anti-endapan', NULL, 'aktuator-01', NULL),
    ('debit_sirkulasi', 'Debit pompa sirkulasi meja', NULL, NULL, NULL)
  ) AS v(sensor, label, tol, perangkat, konstanta)
 WHERE k.sensor = v.sensor;

CREATE TABLE IF NOT EXISTS kalibrasi_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sensor varchar(32) NOT NULL REFERENCES kalibrasi_sensor(sensor) ON DELETE CASCADE ON UPDATE CASCADE,
  dilakukan_pada timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  nilai_ref numeric(10,3),
  bacaan_sebelum numeric(10,3),
  bacaan_sesudah numeric(10,3),
  lulus boolean,
  konstanta_lama jsonb,
  konstanta_baru jsonb,
  catatan text,
  oleh_user_id bigint REFERENCES users(id) ON DELETE SET NULL,
  oleh_label varchar(120)
);
CREATE INDEX IF NOT EXISTS idx_kalibrasi_log_sensor ON kalibrasi_log (sensor, dilakukan_pada DESC);

COMMIT;
