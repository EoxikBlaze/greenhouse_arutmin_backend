-- Saklar per aktuator + tabel uji_lab (hasil uji laboratorium buah/sayur).
-- Idempoten. Tidak menghapus apa pun.
BEGIN;

-- ── 1. saklar_aktuator ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS saklar_aktuator (
  kode         varchar(24)  PRIMARY KEY,
  nama         varchar(60)  NOT NULL,
  aktif        boolean      NOT NULL DEFAULT false,
  diubah_oleh  bigint       REFERENCES users(id) ON DELETE SET NULL,
  diubah_pada  timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_saklar_aktuator_diubah_oleh ON saklar_aktuator (diubah_oleh);
COMMENT ON TABLE saklar_aktuator IS
  'Saklar izin per aktuator. OFF = otomasi (preset/jadwal/AI) tidak boleh menyalakannya; dosing manual tetap boleh (override manual).';
COMMENT ON COLUMN saklar_aktuator.kode IS 'nutrisi_ab | ph_up | ph_down | pengenceran | isi_air';

-- nilai awal diambil dari saklar lama di konfigurasi_dosis (bila ada); tanpa nilai lama = OFF (aman)
INSERT INTO saklar_aktuator (kode, nama, aktif)
SELECT v.kode, v.nama, COALESCE((SELECT k.nilai > 0 FROM konfigurasi_dosis k WHERE k.param = v.param_lama), false)
  FROM (VALUES
    ('nutrisi_ab',  'Nutrisi A + B',      'saklar_ab'),
    ('ph_up',       'pH Up',              'saklar_ph_up'),
    ('ph_down',     'pH Down',            'saklar_ph_down'),
    ('pengenceran', 'Pengenceran air',    'saklar_pengenceran'),
    ('isi_air',     'Pengisian air',      'mode_isi_otomatis')
  ) AS v(kode, nama, param_lama)
ON CONFLICT (kode) DO NOTHING;

-- ── 2. uji_lab ───────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS uji_lab (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kategori            varchar(8)   NOT NULL CHECK (kategori IN ('buah', 'sayur')),
  tanggal             date         NOT NULL DEFAULT CURRENT_DATE,
  parameter           varchar(40)  NOT NULL,
  nilai               numeric(12,4) NOT NULL,
  satuan              varchar(16),
  catatan             text,
  id_siklus_budidaya  bigint REFERENCES siklus_budidaya(id) ON DELETE SET NULL,
  dicatat_oleh        bigint REFERENCES users(id) ON DELETE SET NULL,
  created_at          timestamp(0) without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_uji_lab_kategori_tanggal ON uji_lab (kategori, tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_uji_lab_parameter ON uji_lab (parameter, tanggal DESC);
CREATE INDEX IF NOT EXISTS idx_uji_lab_siklus ON uji_lab (id_siklus_budidaya);
CREATE INDEX IF NOT EXISTS idx_uji_lab_pencatat ON uji_lab (dicatat_oleh);
COMMENT ON TABLE uji_lab IS
  'Hasil uji laboratorium hasil panen (kategori buah/sayur): satu baris per parameter (pH, EC/PPM, brix, ukuran, bobot, ...). Bukan Uji Lab kalibrasi takaran (itu di kalibrasi_log).';

COMMIT;
